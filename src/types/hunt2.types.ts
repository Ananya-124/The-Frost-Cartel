export type Hunt2Actor = 'archivist' | 'tracker';
export type Hunt2Challenge = 1 | 2 | 3 | 4 | 5;
export type Hunt2Input = 'door' | 'characteristic' | 'manifestation' | 'arrangement' | 'anchor-pattern' | 'anchor' | 'final-sequence';
export type Hunt2Observation = {
  id: string;
  title: string;
  location: string;
  discoveredBy: Hunt2Actor | 'team';
  content: string;
  verified: boolean;
  challenge: Hunt2Challenge;
  createdAt: string;
};
export type Hunt2State = {
  teamId: string;
  currentChallenge: Hunt2Challenge;
  completed: boolean;
  subtasks: Record<string, boolean>;
  objectStates: Record<string, 'hidden' | 'visible' | 'inspected' | 'identified' | 'opened' | 'restored' | 'activated' | 'destroyed' | 'dispelled'>;
  observations: Hunt2Observation[];
  hintUses: Record<string, number>;
  score: number;
  penalties: number;
  scoreBreakdown: { exit: number; identity: number; reconstruction: number; anchor: number; final: number; optional: number; penalties: number };
  doorAnswer: number | null;
  characteristic: string | null;
  inspectedManifestations: string[];
  originalArrangement: string[];
  inspectedFurniture: string[];
  anchorPattern: string | null;
  inspectedAnchors: string[];
  trueAnchor: string | null;
  finalSequence: string[];
  mechanismsActivated: string[];
  projectorMaintained: boolean;
  readyBy: Partial<Record<Hunt2Actor, boolean>>;
  activatedBy: Partial<Record<Hunt2Actor, number>>;
  syncDeadline: number | null;
  entityState: { falseCorridorUntil: number | null; decoyHiddenUntil: number | null; trueAnchorHiddenUntil: number | null; memoryStable: boolean; deceptionSuppressed: boolean };
  updatedAt: string;
};
export type Hunt2ActionResult = { success: boolean; message: string; state: Hunt2State; input?: Hunt2Input; hint?: string };
