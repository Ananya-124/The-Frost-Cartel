export type Hunt2Actor = 'archivist' | 'tracker';
export type Hunt2Challenge = 2 | 3 | 4 | 5;
export type Hunt2Input = 'weakness-history' | 'weakness-conclusion' | 'weakness-frequency' | 'weakness-light' | 'weakness-temperature' | 'broken-historical' | 'broken-structure' | 'anchor-history-config' | 'anchor-physical-config' | 'final-sequence';
export type Hunt2Observation = {
  id: string;
  title: string;
  location: string;
  discoveredBy: Hunt2Actor | 'team';
  content: string;
  verified: boolean;
  challenge: Hunt2Challenge;
  createdAt: string;
};
export type Hunt2State = {
  teamId: string;
  currentChallenge: Hunt2Challenge;
  completed: boolean;
  subtasks: Record<string, boolean>;
  objectStates: Record<string, 'hidden' | 'visible' | 'inspected' | 'identified' | 'opened' | 'restored' | 'activated' | 'destroyed' | 'dispelled'>;
  observations: Hunt2Observation[];
  hintUses: Record<string, number>;
  score: number;
  penalties: number;
  scoreBreakdown: { hiddenWeakness: number; brokenMemory: number; anchor: number; final: number; optional: number; penalties: number };
  hiddenWeakness: { archiveEvidence: string[]; experiments: { variable: string; setting: string; result: string }[]; resourcesRemaining: number; instability: number; stationReady: string | null; historicalConclusion: string | null; historicalValid: boolean; experimentalConclusion: string | null; experimentalValid: boolean; trackerActivatedAt: number | null; syncDeadline: number | null };
  brokenMemory: { archivistEvidence: string[]; trackerEvidence: string[]; historical: string[] | null; historicalValid: boolean; structure: string[] | null; structureValid: boolean; archivistSyncAt: number | null; syncDeadline: number | null; corruption: number };
  memoryAnchor: { archivistEvidence: string[]; trackerEvidence: string[]; nodeStates: Record<'A' | 'B' | 'C' | 'D', 'unknown' | 'stable' | 'unstable' | 'reversed' | 'disconnected'>; historicalConfiguration: string[] | null; historicalValid: boolean; physicalConfiguration: string[] | null; physicalValid: boolean; attemptsRemaining: number; instability: number; archivistSyncAt: number | null; syncDeadline: number | null; finalSequenceIndex: number; finalSequenceDeadline: number | null };
  finalSequence: string[];
  mechanismsActivated: string[];
  projectorMaintained: boolean;
  readyBy: Partial<Record<Hunt2Actor, boolean>>;
  activatedBy: Partial<Record<Hunt2Actor, number>>;
  syncDeadline: number | null;
  entityState: { falseCorridorUntil: number | null; trueAnchorHiddenUntil: number | null; memoryStable: boolean; deceptionSuppressed: boolean };
  updatedAt: string;
};
export type Hunt2ActionResult = { success: boolean; message: string; state: Hunt2State; input?: Hunt2Input; hint?: string };
